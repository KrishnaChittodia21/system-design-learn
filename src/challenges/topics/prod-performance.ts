// boe-4: reports 300 req/s × 25 ms of sync CPU; other endpoints 3,000 req/s total (500 per pod at 6 pods) × 1 ms.
const P: Expr = { knob: 'P' };
const W: Expr = { knob: 'W' };
const V: Expr = { knob: 'V' };
const noWorkers = { left: W, op: '==' as const, right: 0 };
/** main-loop utilisation per pod: other endpoints (3,000 ms/s fleet-wide) + the transform when it is not offloaded (7,500 ms/s) */
const mainUtil: Expr = {
  op: 'div',
  args: [{ op: 'add', args: [3000, { op: 'if', cond: noWorkers, then: 7500, else: 0 }] }, { op: 'mul', args: [P, 1000] }],
};
/** worker-pool utilisation per pod: 7.5 cores of transform fleet-wide, spread over P × W workers */
const workerUtil: Expr = { op: 'if', cond: noWorkers, then: 0, else: { op: 'div', args: [7.5, { op: 'mul', args: [P, W] }] } };
/** queueing: wait ≈ service time × 1 ÷ (1 − utilisation) */
const waitX = (u: Expr): Expr => ({ op: 'fn', fn: 'mm1Latency', args: [1, u] });

