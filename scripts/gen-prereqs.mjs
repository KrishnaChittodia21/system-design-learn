// Generates src/content/prereqs.ts: for every Miscellaneous concept section, the in-depth
// section(s) elsewhere in the app that teach it ("Learn this first" links).
// Usage: node --no-warnings scripts/gen-prereqs.mjs   (re-run after content changes)
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/content/topics');

// Hand-checked corrections where text similarity prefers an incident or case study over the core lesson.
// Keyed by the start of the misc section heading; values are [topicId, sectionNumber (1-based)].
const OVERRIDES = {
  'Kafka —': [['mq-fundamentals', 3], ['mq-fundamentals', 8]],
  'Sharding —': [['db-sharding', 3], ['db-sharding', 4]],
  'Transactions —': [['db-fundamentals', 6], ['db-fundamentals', 9]],
  'Rate Limiting —': [['rate-limiting', 1], ['rate-limiting', 8]],
  'Redis Sentinel —': [['cache-fundamentals', 7], ['db-replication', 8]],
};
// Core teaching phases win ties against incident write-ups, case studies and LLD.
const PHASE_WEIGHT = { production: 0.75, designs: 0.75, lld: 0.85 };

const STOP = new Set(
  'the a an and or of to in on for is are be it this that with as at by from what which when why how does do not but if then than can will would should into your you its their they them was were has have had use using used per each any all one two more most less very only also so such there these those our we i'.split(' '),
);
const tokens = (s) =>
  s.toLowerCase().replace(/[`*_#>|[\]()]/g, ' ').split(/[^a-z0-9+]+/).filter((w) => w.length > 2 && !STOP.has(w) && !/^\d+$/.test(w));
const tf = (ws, k = 1, m = new Map()) => {
  for (const w of ws) m.set(w, (m.get(w) ?? 0) + k);
  return m;
};

const topics = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts'))) topics.push((await import(pathToFileURL(join(dir, f)).href)).default);
const byId = new Map(topics.map((t) => [t.id, t]));
const deep = topics.filter((t) => t.phase !== 'miscellaneous').flatMap((t) => t.sections.map((s, i) => ({ t, i, s })));
const docs = deep.map(({ s }) => tf(tokens(s.heading), 4, tf(tokens(s.body), 1, tf(tokens((s.keyPoints ?? []).join(' ')), 2))));
const df = new Map();
docs.forEach((d) => d.forEach((_, w) => df.set(w, (df.get(w) ?? 0) + 1)));
const idf = (w) => Math.log((docs.length + 1) / ((df.get(w) ?? 0) + 0.5));
const vec = (m) => new Map([...m].map(([w, f]) => [w, (1 + Math.log(f)) * idf(w)]));
const norm = (v) => Math.sqrt([...v.values()].reduce((a, x) => a + x * x, 0));
const dv = docs.map(vec);
const dn = dv.map(norm);
const cos = (a, an, b, bn) => {
  let d = 0;
  a.forEach((x, w) => {
    const y = b.get(w);
    if (y) d += x * y;
  });
  return an && bn ? d / (an * bn) : 0;
};

const out = {};
for (const t of topics.filter((x) => x.phase === 'miscellaneous').sort((a, b) => a.order - b.order)) {
  out[t.id] = {};
  for (const s of t.sections) {
    const override = Object.entries(OVERRIDES).find(([prefix]) => s.heading.startsWith(prefix));
    let links;
    if (override) {
      links = override[1].map(([topic, n]) => {
        if (!byId.get(topic)?.sections[n - 1]) throw new Error(`override target ${topic} §${n} does not exist`);
        return { topic, section: n - 1 };
      });
    } else {
      const q = vec(tf(tokens(s.heading), 4, tf(tokens(s.body))));
      const qn = norm(q);
      const ranked = dv
        .map((v, k) => ({ k, score: cos(q, qn, v, dn[k]) * (PHASE_WEIGHT[deep[k].t.phase] ?? 1) }))
        .sort((a, b) => b.score - a.score);
      const [first, second] = ranked;
      links = [first, ...(second && second.score >= 0.6 * first.score ? [second] : [])].map(({ k }) => ({
        topic: deep[k].t.id,
        section: deep[k].i,
      }));
    }
    out[t.id][s.heading] = links;
  }
}

const body = `// GENERATED by scripts/gen-prereqs.mjs — do not edit by hand; edit OVERRIDES in the script and re-run.
// Miscellaneous topic id → concept section heading → in-depth sections that teach it (0-based section index).
export interface PrereqLink {
  topic: string;
  section: number;
}

export const PREREQS: Record<string, Record<string, PrereqLink[]>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'src/content/prereqs.ts'), body);
const n = Object.values(out).reduce((a, m) => a + Object.keys(m).length, 0);
console.log(`wrote src/content/prereqs.ts: ${n} concepts linked`);
